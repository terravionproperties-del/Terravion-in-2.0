#!/usr/bin/env node
/**
 * Builds `content/i18n/index.ts` from whatever translation overlays exist.
 *
 * Why a generated index rather than reading the filesystem at request time: the
 * article routes are statically prerendered, and `availableLocales` has to be
 * known *while* metadata is generated, so hreflang can be emitted only for the
 * locales a page genuinely has. A build-time map gives that synchronously and
 * keeps the overlays code-split — each is a dynamic import, so an English
 * request never pulls Telugu prose into the bundle.
 *
 * Layout it scans:
 *
 *   content/i18n/<locale>/<kind>/<slug>.ts   →  export const translation = {...}
 *
 * where <kind> is blog | guides | locations. A slug with no overlay simply does
 * not appear, and the reader gets the English original with a notice — which is
 * the honest state, and the one the sitemap and the hreflang tags both agree
 * with.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = join(root, "content/i18n");
const KINDS = ["blog", "guides", "locations"];
const LOCALES = ["te", "hi"]; // English is the source, never an overlay

mkdirSync(ROOT, { recursive: true });

/** `{ blog: { "hmda-vs-dtcp": ["te"] }, … }` — bodies only. */
const found = Object.fromEntries(KINDS.map((k) => [k, {}]));
const overlays = [];
/** `[{ locale: "te", kind: "guides" }]` — one card map per locale per kind. */
const cardMaps = [];

for (const locale of LOCALES) {
  for (const kind of KINDS) {
    const dir = join(ROOT, locale, kind);
    if (!existsSync(dir)) continue;

    for (const file of readdirSync(dir).sort()) {
      if (!file.endsWith(".ts") || file === "index.ts") continue;
      const slug = file.replace(/\.ts$/, "");
      overlays.push({ locale, kind, slug });

      // `TRANSLATED` drives hreflang, the sitemaps and the article route's
      // "does this exist in your language" guard, so it must mean *body*, not
      // *file*. A card-first pass produces overlays with a title and an intro
      // and no prose; listing them here would advertise a Telugu URL that
      // serves English paragraphs, which discounts the whole language cluster.
      const src = readFileSync(join(dir, file), "utf8");
      if (/^\s*body:\s*[`"']/m.test(src)) (found[kind][slug] ??= []).push(locale);
    }
  }

  // Card translations: one module per kind, holding every slug's title and
  // summary. A per-slug file would mean 72 dynamic imports to draw one journal
  // listing; this is one.
  const cardDir = join(ROOT, locale, "cards");
  if (!existsSync(cardDir)) continue;
  for (const kind of KINDS) {
    if (existsSync(join(cardDir, `${kind}.ts`))) cardMaps.push({ locale, kind });
  }
}

const lines = [
  "// AUTO-GENERATED by scripts/gen-translation-index.mjs — do not edit by hand.",
  "",
  'import type {',
  "  CardTranslation,",
  "  ContentTranslation,",
  "  TranslationKind,",
  '} from "@/lib/content/translated";',
  "",
  "/**",
  " * Which locales each slug has a translated body for.",
  " *",
  " * Read synchronously while metadata is generated, so a page can advertise",
  " * hreflang only for the languages it actually exists in.",
  " */",
  "export const TRANSLATED: Record<TranslationKind, Record<string, string[]>> = " +
    JSON.stringify(found, null, 2) +
    ";",
  "",
  "/**",
  " * Dynamic importers, one per overlay. Literal specifiers on purpose: a",
  " * template literal would make the bundler pull every language's prose into a",
  " * single context chunk.",
  " */",
  "export const LOADERS: Record<",
  "  string,",
  "  () => Promise<{ translation: ContentTranslation }>",
  "> = {",
];

for (const { locale, kind, slug } of overlays) {
  lines.push(
    `  ${JSON.stringify(`${locale}:${kind}:${slug}`)}: () => import("./${locale}/${kind}/${slug}"),`
  );
}

lines.push(
  "};",
  "",
  "/**",
  " * Card translations — title, summary and metadata for a listing page.",
  " *",
  " * Keyed `<locale>:<kind>`, one module per collection rather than one per",
  " * slug, because a listing page needs all of them at once.",
  " */",
  "export const CARD_LOADERS: Record<",
  "  string,",
  "  () => Promise<{ cards: Record<string, CardTranslation> }>",
  "> = {"
);

for (const { locale, kind } of cardMaps) {
  lines.push(`  ${JSON.stringify(`${locale}:${kind}`)}: () => import("./${locale}/cards/${kind}"),`);
}

lines.push("};", "");

writeFileSync(join(ROOT, "index.ts"), lines.join("\n"));

const perKind = KINDS.map((k) => `${k}=${Object.keys(found[k]).length}`).join(" ");
console.log(
  `content/i18n/index.ts — ${overlays.length} overlays, bodies (${perKind}) — ` +
    `${cardMaps.length} card maps (${cardMaps.map((c) => `${c.locale}:${c.kind}`).join(" ") || "none"})`
);
