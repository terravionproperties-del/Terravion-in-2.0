// Generates content/{blog,guides,locations}/index.ts from the files present.
// Run after adding or removing content modules: node scripts/gen-content-index.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const collections = [
  { dir: "content/blog", exportName: "post", listName: "posts", type: "BlogPost" },
  { dir: "content/guides", exportName: "guide", listName: "guides", type: "GuideContent" },
  { dir: "content/locations", exportName: "location", listName: "locations", type: "LocationContent" },
];

for (const c of collections) {
  const abs = join(root, c.dir);
  let files;
  try {
    files = readdirSync(abs)
      .filter((f) => f.endsWith(".ts") && f !== "index.ts")
      .sort();
  } catch {
    continue;
  }
  const idents = files.map((f, i) => `m${i}`);
  const imports = files
    .map((f, i) => `import { ${c.exportName} as m${i} } from "./${f.replace(/\.ts$/, "")}";`)
    .join("\n");
  const body = `// AUTO-GENERATED by scripts/gen-content-index.mjs — do not edit by hand.
import type { ${c.type} } from "@/lib/types";
${imports}

export const ${c.listName}: ${c.type}[] = [${idents.join(", ")}];

export function getBySlug(slug: string): ${c.type} | undefined {
  return ${c.listName}.find((x) => x.slug === slug);
}
`;
  writeFileSync(join(abs, "index.ts"), body);
  console.log(`${c.dir}/index.ts — ${files.length} entries`);
}
